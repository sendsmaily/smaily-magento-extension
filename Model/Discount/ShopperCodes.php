declare(strict_types=1);

namespace Smaily\Connect\Model\Discount;

use Magento\Framework\App\ResourceConnection;
use Magento\SalesRule\Helper\Coupon as CouponHelper;
use Smaily\Connect\Model\Automation\Trigger;

/**
 * The discount codes the extension made for one address (CON-225), for a
 * data-subject export and erasure (Privacy\LocalEraser), as the WooCommerce
 * plugin lists and erases its own (its CON-213).
 *
 * A Magento coupon holds no address, so the codes are found through the
 * automation rows of the event queue: inPayload() reads the codes a row's
 * stored address carries (AutomationDiscount puts them there before the
 * post), only when that address is this one — any letter case, while an
 * address that differs by an accent or a character belongs to someone else.
 * A code counts only while it is still one of the extension's in
 * `salesrule_coupon` (auto-generated, last day written by CouponExpiry), so
 * a coupon the merchant made is never touched.
 *
 * Erasure deletes an unused code. A used one stays: its order still names
 * it, and the code itself holds nothing of the shopper — erasing the queue
 * row that named the address is what detaches it, so it is counted as
 * anonymised. A code is used once Magento counted the use or an order
 * carries it: Magento counts the use later, through its message queue.
 */
class ShopperCodes
{
    /**
     * The sales connection, where LocalEraser reads the orders too.
     */
    private const SALES_CONNECTION = 'sales';

    public function __construct(
        private readonly ResourceConnection $resourceConnection
    ) {
    }

    /**
     * The discount codes a queued automation payload carries for this
     * address (already lowercased and trimmed).
     *
     * @param array<int|string, mixed>|null $payload a row's decoded payload
     * @return string[]
     */
    public function inPayload(?array $payload, string $email): array
    {
        $address = $payload['address'] ?? null;
        if (!is_array($address) || strtolower(trim((string)($address['email'] ?? ''))) !== $email) {
            return [];
        }

        $codes = [];
        foreach (Trigger::COUPON_FIELDS as [$codeField]) {
            $code = $address[$codeField] ?? null;
            if (is_string($code) && $code !== '') {
                $codes[] = $code;
            }
        }

        return $codes;
    }

    /**
     * Each of the codes that is the extension's: the code, when it was made
     * (UTC), its last valid day (store time) and whether it was used.
     *
     * @param string[] $codes
     * @return array<int, array{code: string, created_at: string, expires_at: string, used: bool}>
     */
    public function export(array $codes): array
    {
        return array_map(
            static fn (array $row): array => [
                'code' => $row['code'],
                'created_at' => $row['created_at'],
                'expires_at' => $row['expires_at'],
                'used' => $row['used'],
            ],
            $this->rows($codes)
        );
    }

    /**
     * Delete the unused ones of the codes; a used one stays with its order.
     *
     * @param string[] $codes
     * @return array{removed: int, anonymised: int}
     */
    public function erase(array $codes): array
    {
        $unused = [];
        $used = 0;
        foreach ($this->rows($codes) as $row) {
            if ($row['used']) {
                $used++;
            } else {
                $unused[] = $row['coupon_id'];
            }
        }

        $removed = 0;
        if ($unused) {
            $removed = $this->resourceConnection->getConnection()->delete(
                $this->resourceConnection->getTableName('salesrule_coupon'),
                ['coupon_id IN (?)' => $unused]
            );
        }

        return ['removed' => $removed, 'anonymised' => $used];
    }

    /**
     * The extension's codes among $codes, oldest first.
     *
     * @param string[] $codes
     * @return array<int, array{coupon_id: int, code: string, created_at: string, expires_at: string, used: bool}>
     */
    private function rows(array $codes): array
    {
        if (!$codes) {
            return [];
        }

        $connection = $this->resourceConnection->getConnection();
        $coupons = $connection->fetchAll(
            $connection->select()
                ->from(
                    $this->resourceConnection->getTableName('salesrule_coupon'),
                    ['coupon_id', 'code', 'created_at', 'expiration_date', 'times_used']
                )
                ->where('code IN (?)', $codes)
                ->where('type = ?', CouponHelper::COUPON_TYPE_SPECIFIC_AUTOGENERATED)
                ->order('coupon_id ASC')
        );
        $coupons = array_values(array_filter(
            $coupons,
            static fn (array $coupon): bool => str_ends_with(
                (string)$coupon['expiration_date'],
                ' ' . CouponExpiry::END_OF_DAY
            )
        ));
        if (!$coupons) {
            return [];
        }

        $sales = $this->resourceConnection->getConnection(self::SALES_CONNECTION);
        $ordered = array_map('strtolower', $sales->fetchCol(
            $sales->select()
                ->distinct()
                ->from(
                    $this->resourceConnection->getTableName('sales_order', self::SALES_CONNECTION),
                    ['coupon_code']
                )
                ->where('coupon_code IN (?)', array_column($coupons, 'code'))
        ));

        return array_map(
            static fn (array $coupon): array => [
                'coupon_id' => (int)$coupon['coupon_id'],
                'code' => (string)$coupon['code'],
                'created_at' => (string)$coupon['created_at'],
                'expires_at' => substr((string)$coupon['expiration_date'], 0, 10),
                'used' => (int)$coupon['times_used'] > 0
                    || in_array(strtolower((string)$coupon['code']), $ordered, true),
            ],
            $coupons
        );
    }
}
