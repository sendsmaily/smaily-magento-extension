namespace Smaily\Connect\Test\Integration\Discount;

use Magento\Quote\Model\Quote;
use Magento\Quote\Model\Quote\Address;
use Magento\SalesRule\Helper\Coupon as CouponHelper;
use Magento\SalesRule\Model\Coupon\Massgenerator;
use Magento\SalesRule\Model\Coupon\MassgeneratorFactory;
use Magento\SalesRule\Model\Rule;
use Magento\SalesRule\Model\Utility;
use Magento\SalesRule\Model\ValidateCoupon;
use Smaily\Connect\Model\Automation\Trigger;
use Smaily\Connect\Model\Config;
use Smaily\Connect\Model\Discount\AutomationDiscount;
use Smaily\Connect\Model\Discount\CodeIssuer;
use Smaily\Connect\Model\Discount\CouponExpiry;
use Smaily\Connect\Model\Discount\RuleSource;
use Smaily\Connect\Model\Discount\StoreDate;
use Smaily\Connect\Model\Queue\Event;
use Smaily\Connect\Model\Queue\EventQueue;
use Smaily\Connect\Model\Queue\EventType;
use Smaily\Connect\Plugin\SalesRule\RejectExpiredCoupon;
