declare(strict_types=1);

namespace Smaily\Connect\Model\Discount;

use Magento\SalesRule\Helper\Coupon as CouponHelper;
use Magento\SalesRule\Model\ResourceModel\Coupon as CouponResource;

/**
 * The last valid day of a discount code an automation sent (CON-198).
 *
 * Magento keeps an `expiration_date` on every coupon but never checks it at
 * checkout (2.4.4–2.4.8: only the rule's own From and To dates count), so
 * the extension checks the day of the codes it made itself
 * (Plugin\SalesRule\RejectExpiredCoupon). It writes that day as
 * `<Y-m-d> 23:59:59` (END_OF_DAY): the last valid day in the store's
 * timezone. Magento itself only ever wrote a rule's To date there, a date
 * without a time, so the time marks the extension's own codes and a coupon
 * the merchant generated in the admin keeps working as before.
 */
class CouponExpiry
{
    public const END_OF_DAY = '23:59:59';

    /**
     * The last valid day of each code looked up in this request ('' when
     * the code is not one of the extension's), by rule id and code.
     *
     * @var array<string, string>
     */
    private array $lastDays = [];

    public function __construct(
        private readonly CouponResource $couponResource,
        private readonly StoreDate $storeDate
    ) {
    }

    /**
     * Records a code's last valid day (`Y-m-d`).
     */
    public function write(string $code, string $lastDay): void
    {
        $this->couponResource->getConnection()->update(
            $this->couponResource->getMainTable(),
            ['expiration_date' => $lastDay . ' ' . self::END_OF_DAY],
            ['code = ?' => $code]
        );
    }

    /**
     * Whether the code is one of the extension's codes of the rule and its
     * last valid day has passed in the store's timezone.
     */
    public function isExpired(string $code, int $ruleId, ?int $storeId): bool
    {
        $key = $ruleId . '|' . $code;
        if (!isset($this->lastDays[$key])) {
            $connection = $this->couponResource->getConnection();
            $expiration = (string)$connection->fetchOne(
                $connection->select()
                    ->from($this->couponResource->getMainTable(), ['expiration_date'])
                    ->where('code = ?', $code)
                    ->where('rule_id = ?', $ruleId)
                    ->where('type = ?', CouponHelper::COUPON_TYPE_SPECIFIC_AUTOGENERATED)
            );
            $this->lastDays[$key] = str_ends_with($expiration, ' ' . self::END_OF_DAY)
                ? substr($expiration, 0, 10)
                : '';
        }

        return $this->lastDays[$key] !== '' && $this->lastDays[$key] < $this->storeDate->today($storeId);
    }
}
