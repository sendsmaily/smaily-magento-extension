/**
 * An automation's discount code (CON-198) on Magento's own coupon tables:
 * the code comes from Magento's coupon generation for the rule, works once
 * (Magento's own coupon check), until the end of its last valid day (the
 * extension's check), and a retried queue row sends the code its first
 * attempt made. The rule itself is the merchant's: its conditions are
 * Magento's, so RuleSource stands in for the rule table here.
 */
class DiscountCodeTest extends IntegrationTestCase
{
    private const RULE_ID = 5;
    private const STORE_ID = 1;
    private const WEBSITE_ID = 1;

    private SchemaInstaller $schema;

    /** The rule's To date ('' for none), or null when it gives no codes. */
    private ?string $ruleToDate = '';

    protected function setUp(): void
    {
        parent::setUp();
        require_once __DIR__ . '/../Support/Stub/CouponFactory.php';
        require_once __DIR__ . '/../Support/Stub/MassgeneratorFactory.php';
        require_once __DIR__ . '/../Support/Stub/CouponUsageFactory.php';
        require_once __DIR__ . '/../Support/Stub/DataObjectFactory.php';
        $this->schema = new SchemaInstaller($this->connection);
        $this->schema->createSalesRuleCouponTables();
    }

    protected function tearDown(): void
    {
        $this->schema->dropSalesRuleCouponTables();
        parent::tearDown();
    }

    public function testACodeIsMadeByMagentoForTheRuleAndWorksOnce(): void
    {
        $coupon = $this->issuer()->issue(self::RULE_ID, 7, self::STORE_ID, self::WEBSITE_ID);

        self::assertNotNull($coupon);
        $rows = $this->fetchAll('salesrule_coupon', 'coupon_id');
        self::assertCount(1, $rows);
        self::assertSame($coupon['code'], $rows[0]['code']);
        self::assertSame(self::RULE_ID, (int)$rows[0]['rule_id']);
        self::assertSame(1, (int)$rows[0]['usage_limit'], 'Uses per Coupon');
        self::assertSame(CouponHelper::COUPON_TYPE_SPECIFIC_AUTOGENERATED, (int)$rows[0]['type']);
        self::assertMatchesRegularExpression('/^[A-Z0-9]{12}$/', $coupon['code'], 'the store\'s code format');

        $validate = $this->objectManager->create(ValidateCoupon::class);
        self::assertTrue($validate->execute($this->rule(), $this->address($coupon['code']), $coupon['code']));
        // What Magento's coupon usage update writes when an order uses it.
        $this->connection->update('salesrule_coupon', ['times_used' => 1], ['code = ?' => $coupon['code']]);
        self::assertFalse(
            $validate->execute($this->rule(), $this->address($coupon['code']), $coupon['code']),
            'a code works once'
        );
    }

    public function testACodeWorksUntilTheEndOfItsLastDay(): void
    {
        $coupon = $this->issuer()->issue(self::RULE_ID, 7, self::STORE_ID, self::WEBSITE_ID);

        self::assertNotNull($coupon);
        $lastDay = gmdate('Y-m-d', $this->clock->now() + 7 * 86400);
        self::assertSame($lastDay, $coupon['expires_at']);
        self::assertSame(
            $lastDay . ' 23:59:59',
            $this->fetchRow('salesrule_coupon', 1, 'coupon_id')['expiration_date']
        );

        self::assertTrue($this->applies($coupon['code']), 'on the day it is sent');
        $this->clock->travel(7 * 86400);
        self::assertTrue($this->applies($coupon['code']), 'on its last day');
        $this->clock->travel(86400);
        self::assertFalse($this->applies($coupon['code']), 'the day after its last day');
    }

    public function testACodeNeverOutlivesItsRule(): void
    {
        $this->ruleToDate = gmdate('Y-m-d', $this->clock->now() + 2 * 86400);

        $coupon = $this->issuer()->issue(self::RULE_ID, 7, self::STORE_ID, self::WEBSITE_ID);

        self::assertNotNull($coupon);
        self::assertSame($this->ruleToDate, $coupon['expires_at']);
    }

    public function testARuleThatGivesNoCodesMakesNone(): void
    {
        $this->ruleToDate = null;

        self::assertNull($this->issuer()->issue(self::RULE_ID, 7, self::STORE_ID, self::WEBSITE_ID));
        self::assertSame([], $this->fetchAll('salesrule_coupon', 'coupon_id'));
    }

    public function testCodesTheExtensionDidNotMakeAreLeftToMagento(): void
    {
        // Generated in the admin: Magento 2.4.4–2.4.6 copied the rule's To
        // date there, 2.4.7 and later nothing.
        $this->connection->insert('salesrule_coupon', [
            'rule_id' => self::RULE_ID, 'code' => 'ADMIN-OLD', 'type' => 1, 'expiration_date' => '2020-01-01 00:00:00',
        ]);
        $this->connection->insert('salesrule_coupon', [
            'rule_id' => self::RULE_ID, 'code' => 'ADMIN-NEW', 'type' => 1, 'expiration_date' => null,
        ]);

        self::assertTrue($this->applies('ADMIN-OLD'));
        self::assertTrue($this->applies('ADMIN-NEW'));
    }

    public function testARetriedRowSendsTheCodeItsFirstAttemptMade(): void
    {
        $this->switchOn();
        $queue = $this->objectManager->create(EventQueue::class);
        $queue->enqueue(EventType::AUTOMATION_TRIGGER, $this->payload(), 'jane@example.com', self::WEBSITE_ID);

        $first = $this->sendAttempt($queue);
        $second = $this->sendAttempt($queue);

        [$codeField, $expiryField] = Trigger::COUPON_FIELDS[Trigger::WELCOME];
        self::assertArrayHasKey($codeField, $first);
        self::assertSame(gmdate('Y-m-d', $this->clock->now() + 7 * 86400), $first[$expiryField]);
        self::assertSame($first, $second, 'the retry sends the same code');
        self::assertCount(1, $this->fetchAll('salesrule_coupon', 'coupon_id'), 'one code for the row');
        $stored = json_decode((string)$this->fetchRow('smaily_event_queue', 1)['payload'], true);
        self::assertSame($first, $stored['address'], 'the code is stored with the queued row');
    }

    public function testARuleThatGivesNoCodesSendsTheEmailWithoutOne(): void
    {
        $this->switchOn();
        $this->ruleToDate = null;
        $queue = $this->objectManager->create(EventQueue::class);
        $queue->enqueue(EventType::AUTOMATION_TRIGGER, $this->payload(), 'jane@example.com', self::WEBSITE_ID);

        self::assertSame(['email' => 'jane@example.com'], $this->sendAttempt($queue));
        $stored = json_decode((string)$this->fetchRow('smaily_event_queue', 1)['payload'], true);
        self::assertSame(
            str_replace('%1', (string)self::RULE_ID, AutomationDiscount::NOTICE_RULE_UNAVAILABLE),
            $stored[AutomationDiscount::NOTICE_KEY]
        );

        // Fixed meanwhile, the rule gives that row no code on a retry.
        $this->ruleToDate = '';
        self::assertSame(['email' => 'jane@example.com'], $this->sendAttempt($queue));
        self::assertSame([], $this->fetchAll('salesrule_coupon', 'coupon_id'));
    }

    public function testWithTheSwitchOffThePayloadStaysAsQueued(): void
    {
        $queue = $this->objectManager->create(EventQueue::class);
        $queue->enqueue(EventType::AUTOMATION_TRIGGER, $this->payload(), 'jane@example.com', self::WEBSITE_ID);
        $queued = $this->fetchRow('smaily_event_queue', 1)['payload'];

        self::assertSame(['email' => 'jane@example.com'], $this->sendAttempt($queue));
        self::assertSame($queued, $this->fetchRow('smaily_event_queue', 1)['payload']);
        self::assertSame([], $this->fetchAll('salesrule_coupon', 'coupon_id'));
    }

    /**
     * One send attempt of the queue's one row: the address it posts, then
     * the row back on the queue, as a failed send leaves it for its retry.
     *
     * @return array<string, mixed>
     */
    private function sendAttempt(EventQueue $queue): array
    {
        $events = $queue->claimBatch();
        self::assertCount(1, $events);
        /** @var Event $event */
        $event = $events[0];
        $address = $this->automationDiscount($queue)->address(
            $event,
            $queue->decodePayload($event),
            Trigger::WELCOME,
            self::STORE_ID,
            self::WEBSITE_ID
        );
        $queue->release($events);

        return $address;
    }

    private function switchOn(): void
    {
        $scopeConfig = $this->env->getScopeConfig();
        $scopeConfig->setValue(Config::XML_PATH_WELCOME_COUPON_ENABLED, '1');
        $scopeConfig->setValue(Config::XML_PATH_WELCOME_COUPON_RULE, (string)self::RULE_ID);
        $scopeConfig->setValue(Config::XML_PATH_WELCOME_COUPON_DAYS, '7');
    }

    /**
     * @return array<string, mixed>
     */
    private function payload(): array
    {
        return [
            'trigger_type' => Trigger::WELCOME,
            'store_id' => self::STORE_ID,
            'website_id' => self::WEBSITE_ID,
            'language' => 'en',
            'address' => ['email' => 'jane@example.com'],
        ];
    }

    private function automationDiscount(EventQueue $queue): AutomationDiscount
    {
        return $this->objectManager->create(AutomationDiscount::class, [
            'issuer' => $this->issuer(),
            'eventQueue' => $queue,
        ]);
    }

    private function issuer(): CodeIssuer
    {
        $rules = $this->createMock(RuleSource::class);
        $rules->method('usable')->willReturnCallback(
            fn (int $ruleId): ?array => $ruleId === self::RULE_ID && $this->ruleToDate !== null
                ? ['to_date' => $this->ruleToDate, 'uses_per_customer' => 0]
                : null
        );
        // The store's code format (Stores > Configuration > Customers >
        // Promotions), Magento's defaults, and Magento's own charsets.
        $helper = $this->createMock(CouponHelper::class);
        $helper->method('getDefaultLength')->willReturn(12);
        $helper->method('getDefaultFormat')->willReturn('1');
        $helper->method('getFormatsList')->willReturn([CouponHelper::COUPON_FORMAT_ALPHANUMERIC => 'Alphanumeric']);
        $helper->method('getCharset')->willReturn(str_split('ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'));
        $helper->method('getCodeSeparator')->willReturn('-');

        // Magento's generator itself, with that helper.
        $generators = $this->createMock(MassgeneratorFactory::class);
        $generators->method('create')->willReturnCallback(
            fn (): Massgenerator => $this->objectManager->create(Massgenerator::class, ['salesRuleCoupon' => $helper])
        );

        return $this->objectManager->create(CodeIssuer::class, [
            'rules' => $rules,
            'generatorFactory' => $generators,
            'couponHelper' => $helper,
        ]);
    }

    /**
     * Whether the extension's check lets the rule apply to a cart with the code.
     */
    private function applies(string $code): bool
    {
        $plugin = new RejectExpiredCoupon($this->objectManager->create(CouponExpiry::class, [
            'storeDate' => $this->objectManager->create(StoreDate::class),
        ]));

        return $plugin->afterCanProcessRule(
            $this->createMock(Utility::class),
            true,
            $this->rule(),
            $this->address($code)
        );
    }

    private function rule(): Rule
    {
        /** @var Rule $rule */
        $rule = (new \ReflectionClass(Rule::class))->newInstanceWithoutConstructor();
        $rule->setData(['id' => self::RULE_ID, 'rule_id' => self::RULE_ID, 'coupon_type' => Rule::COUPON_TYPE_SPECIFIC]);

        return $rule;
    }

    private function address(string $code): Address
    {
        /** @var Quote $quote */
        $quote = (new \ReflectionClass(Quote::class))->newInstanceWithoutConstructor();
        $quote->setData(['store_id' => self::STORE_ID, 'coupon_code' => $code]);
        /** @var Address $address */
        $address = (new \ReflectionClass(Address::class))->newInstanceWithoutConstructor();
        $address->setQuote($quote);

        return $address;
    }
}
